def coefficient_audit():
    dp = {0: 1}
    for k in range(1, 42):
        qm = qmin_exact(k)
        nd = {}
        for q, count in dp.items():
            if q >= qm:
                nd[q] = nd.get(q, 0) + count
            if q + 1 >= qm:
                nd[q + 1] = nd.get(q + 1, 0) + count
        dp = nd
        assert (qm, sum(dp.values())) == EXPECTED_COEFF[k], (k, qm, sum(dp.values()))
    return True


def lineage_audit():
    for k in range(33, 42):
        calc = {}
        for q, count in SURV[k - 1].items():
            calc[q] = calc.get(q, 0) + count
            calc[q + 1] = calc.get(q + 1, 0) + count
        qmin = min(PREF[k])
        calc = {q: c for q, c in calc.items() if q >= qmin}
        assert calc == PREF[k], (k, calc, PREF[k])
    return True


def total_accounting_audit():
    for k in range(32, 42):
        L, P, S, new, cumulative = LEDGER_TOTALS[k]
        assert L == EXPECTED_COEFF[k][1]
        assert P == sum(PREF[k].values()) if k >= 33 else P == 33_894_412
        assert S == sum(SURV[k].values())
        assert P - S == new
        assert L - S == cumulative
    return True


